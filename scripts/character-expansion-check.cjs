async page => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:4175', { waitUntil: 'networkidle' });
  const skip = page.getByRole('button', { name: /Skip intro/ });
  if (await skip.isVisible()) await skip.click();
  const rana = page.locator('.ic-stage[data-character="rana"]');
  const shobu = page.locator('.ic-stage[data-character="shobu"]');
  const glass = page.locator('.glass-break-effect');
  await rana.scrollIntoViewIfNeeded();
  await page.waitForTimeout(700);
  await rana.locator('button').click();
  assert(await glass.getAttribute('data-state') === 'pending', 'Rana strike has no preparation delay');
  const activation = await rana.getAttribute('data-activations');
  await rana.locator('button').click();
  assert(await rana.getAttribute('data-activations') === activation, 'Repeated click restarted active strike');
  await page.waitForTimeout(450);
  assert(await glass.getAttribute('data-state') === 'broken', 'V2 glass fracture missing at impact');
  assert(await glass.locator('path').count() === 39, 'V2 fracture rays or branches missing');
  const overlay = await glass.evaluate(e => { const r=e.getBoundingClientRect(); return { x:r.x,y:r.y,width:r.width,height:r.height,pointer:getComputedStyle(e).pointerEvents }; });
  assert(overlay.x === 0 && overlay.y === 0 && overlay.width === 1440 && overlay.height === 1000 && overlay.pointer === 'none', 'Glass overlay bounds or pointer behavior wrong');
  await page.screenshot({ path: 'output/playwright/rana-glass-desktop.png' });
  await page.waitForTimeout(2600);
  assert(await glass.getAttribute('data-state') === 'idle', 'Fracture failed to heal');
  await rana.locator('button').focus();
  await page.keyboard.press('Enter');
  await page.waitForTimeout(430);
  assert(await glass.getAttribute('data-state') === 'broken', 'Keyboard strike failed');
  await page.locator('#contact').scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  assert(await glass.getAttribute('data-state') === 'idle', 'Offscreen fracture did not clear');
  await shobu.scrollIntoViewIfNeeded();
  await page.waitForTimeout(700);
  await page.getByRole('button', { name: 'Pause character idle animations' }).click();
  await shobu.scrollIntoViewIfNeeded();
  await shobu.locator('button').press('Space');
  const walk = await shobu.evaluate(e => new Promise(resolve => {
    const frames = [], travel = []; const start = performance.now();
    const sample = () => { frames.push(Number(e.querySelector('.ic-sprite').dataset.frame)); travel.push(parseFloat(e.style.getPropertyValue('--ic-walk-x')) || 0); if (performance.now() - start < 2200) setTimeout(sample, 45); else resolve({frames,travel}); }; sample();
  }));
  assert([2,3,4,5].every(frame => walk.frames.includes(frame)), 'Shobu four-frame walking gait missing');
  assert(Math.max(...walk.travel) > 10, 'Shobu does not move when walking');
  assert(await glass.getAttribute('data-state') === 'idle', 'Shobu triggered Rana effect');
  await page.locator('.pc-person-shobu').screenshot({ path: 'output/playwright/shobu-walking-desktop.png' });
  await page.waitForTimeout(650);
  assert(await shobu.getAttribute('data-action') === 'idle', 'Shobu did not return to standing');
  await page.locator('.pc-person-shobu').screenshot({ path: 'output/playwright/shobu-standing-desktop.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await rana.scrollIntoViewIfNeeded();
  // The earlier keyboard strike pauses offscreen and resumes on return.
  await rana.locator('button[aria-busy="false"]').waitFor();
  await rana.locator('button').click();
  assert(await glass.getAttribute('data-state') === 'broken' && await glass.getAttribute('data-motion') === 'reduced', 'Reduced-motion static fracture missing');
  assert(await glass.locator('svg').evaluate(e => !getComputedStyle(e).animationName.includes('glass-break-impact')), 'Reduced motion has impact shake');
  await page.screenshot({ path: 'output/playwright/rana-glass-mobile-reduced.png' });
  await page.waitForTimeout(900);
  assert(await glass.getAttribute('data-state') === 'idle', 'Reduced fracture did not clear');
  await shobu.scrollIntoViewIfNeeded();
  await shobu.locator('button').click();
  assert(await shobu.getAttribute('data-action') === 'walk', 'Reduced Shobu interaction missing');
  assert(await shobu.locator('.ic-sprite').getAttribute('data-frame') === '0', 'Reduced walk should stay standing');
  await page.locator('.pc-person-shobu').screenshot({ path: 'output/playwright/shobu-mobile-reduced.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflows');
  assert(errors.length === 0, errors.join('\n'));
  return { rana: '39 V2 fracture paths, delayed impact, keyboard, repeat guard, autoheal, offscreen cleanup', shobu: 'standing, four gait frames, travel, pause-safe click', reducedMotion: 'static feedback and no impact shake', overlay, errors };
}
