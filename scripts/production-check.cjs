async (page) => {
 const messages=[];
 const onConsole=m=>{if(m.type()==='error'||m.type()==='warning') messages.push(m.text());};
 const onError=e=>messages.push(e.message);
 page.on('console',onConsole);page.on('pageerror',onError);
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://localhost:4174/');
 await page.waitForFunction(()=>document.querySelector('.hero-actions') && getComputedStyle(document.querySelector('.hero-actions')).opacity==='1');
 const button=page.getByRole('link',{name:'Explore the vision'});
 await button.hover();
 await page.screenshot({path:'output/playwright/production-desktop.png'});
 await page.getByRole('button',{name:'Explore the Mumbai nights creative direction'}).click();
 await page.getByRole('dialog').waitFor({state:'visible'});
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:320,height:800});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.keyboard.press('Escape');
 const bounds=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.reload();
 await page.locator('.fx-hero-atmosphere').waitFor({state:'attached'});
 const reduced=await page.evaluate(()=>({heroPixels:getComputedStyle(document.querySelector('.fx-hero-atmosphere')).display,ticker:getComputedStyle(document.querySelector('.ticker-track')).animationName,client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 await page.screenshot({path:'output/playwright/production-320.png'});
 await page.setViewportSize({width:1920,height:1080});
 const wide=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 page.off('console',onConsole);page.off('pageerror',onError);
 await page.goto('http://localhost:5174/');
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.reload();
 await page.setViewportSize({width:1440,height:1000});
 return {messages,bounds,reduced,wide,title:await page.title()};
}
